/** شماره‌ی مطلق روز (از سال ۱۹۷۰) برای انتخاب قطعی جمله در هر روز */
function absoluteDayNumber(dateKey: string): number {
  return Math.floor(new Date(`${dateKey}T00:00:00Z`).getTime() / 86_400_000);
}

/**
 * جمله‌ی امروز: با گذشت هر روز یک جمله جلو می‌رویم و وقتی به آخر لیست
 * رسیدیم دوباره از اول – بنابراین تا `QUOTES.length` روز هیچ تکراری نیست.
 * `offset` برای نمایش «جمله‌ی بعدی» هنگام فشردن دکمه‌ی جابه‌جایی به کار می‌رود.
 */
export function quoteOfTheDay(dateKey: string, offset = 0): Quote {
  const i = (((absoluteDayNumber(dateKey) % QUOTES.length) + offset) % QUOTES.length + QUOTES.length) % QUOTES.length;
  return QUOTES[i];
}
