/** ورودی‌های جدیدتر از نسخه‌ی دیده‌شده (برای نمایش «چی جدیده؟») */
export function unseenChangelog(lastSeen: string | undefined): ChangelogEntry[] {
  if (!lastSeen) return CHANGELOG.slice(0, 1);
  // مقایسه‌ی ساده‌ی semver
  const newer = (a: string, b: string) => {
    const pa = a.split(".").map(Number);
    const pb = b.split(".").map(Number);
    for (let i = 0; i < 3; i++) {
      if ((pa[i] ?? 0) !== (pb[i] ?? 0)) return (pa[i] ?? 0) > (pb[i] ?? 0);
    }
    return false;
  };
  return CHANGELOG.filter((e) => newer(e.version, lastSeen));
}
