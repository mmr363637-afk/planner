/** جدیدترین نسخه‌ای که یادداشت انتشارش در اپ موجود است. */
export const LATEST_CHANGELOG_VERSION = CHANGELOG[0]?.version ?? "0.0.0";

function compareVersions(a: string, b: string): number {
  const pa = a.split(".").map((part) => Number(part) || 0);
  const pb = b.split(".").map((part) => Number(part) || 0);
  for (let i = 0; i < 3; i++) {
    if ((pa[i] ?? 0) !== (pb[i] ?? 0)) {
      return (pa[i] ?? 0) > (pb[i] ?? 0) ? 1 : -1;
    }
  }
  return 0;
}

/** ورودی‌های جدیدتر از نسخه‌ی یادداشتِ واقعاً دیده‌شده (برای نمایش «چی جدیده؟») */
export function unseenChangelog(
  lastSeenAppVersion: string | undefined,
  lastSeenNotesVersion?: string,
): ChangelogEntry[] {
  // در بیلدهای قدیمی، lastSeenVersion هنگام بستنِ یادداشت قدیمی به نسخهٔ اپ ارتقا
  // می‌یافت، حتی اگر یادداشت‌های 1.20/1.21 اصلاً در بیلد نبودند. برای یک‌بار،
  // کاربرانی که نسخهٔ اپ 1.20+ را دیده‌اند ولی هنوز نشانگرِ یادداشت ندارند، از 1.19
  // حساب می‌شوند تا هر دو نسخهٔ جاافتاده را ببینند.
  const seenVersion = lastSeenNotesVersion ?? (
    lastSeenAppVersion && compareVersions(lastSeenAppVersion, "1.20.0") >= 0
      ? "1.19.0"
      : lastSeenAppVersion
  );
  if (!seenVersion) return CHANGELOG.slice(0, 1);
  return CHANGELOG.filter((entry) => compareVersions(entry.version, seenVersion) > 0);
}
