// ===== مولد شبه‌تصادفی قطعی (اشتراکی بین موتور صدا و موتور موسیقی) =====
// خروجی کاملاً قطعی است تا در تست‌ها قابل تکرار باشد و همان رفتار داخل مرورگر دیده شود.

/** مولد شبه‌تصادفی قطعی تا خروجی در اجراهای مختلف یکسان و قابل تست باشد */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
